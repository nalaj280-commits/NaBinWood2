int RenderTitle()
{
	if (asc == 1)
	{
		ASCII();
		asc = 0;
	}

	set_color(BG_COLOR_RED);
	set_color(FONT_COLOR_WHITE);
	move_cursor(120, 9);
	printf("                      ");
	move_cursor(120, 10);
	printf("  이은석:추격의시작   ");
	move_cursor(120, 11);
	printf("                      ");

	set_color(BG_COLOR_BLACK);

	if (menu == 1)
	{
		set_color(BG_COLOR_YELLOW);
	}
	move_cursor(120, 13);
	printf("  1. 게임시작  ");
	set_color(BG_COLOR_BLACK);

	if (menu == 2)
	{
		set_color(BG_COLOR_YELLOW);
	}
	move_cursor(120, 15);
	printf("  2. 게임설명  ");
	set_color(BG_COLOR_BLACK);

	if (menu == 3)
	{
		set_color(BG_COLOR_YELLOW);
	}
	move_cursor(120, 17);
	printf("  3. 팀소개  ");
	set_color(BG_COLOR_BLACK);

	if (menu == 4)
	{
		set_color(BG_COLOR_YELLOW);
	}
	move_cursor(120, 19);
	printf("  4. 게임종료  ");
	set_color(BG_COLOR_BLACK);



	char a = getch();
	switch (a)
	{
	case 'w':
		if (menu > 1)
		{
			menu = menu - 1;
		}
		break;
	case 's':
		if (menu < 4)
		{
			menu = menu + 1;
		}
		break;
	case 13:
		if (menu == 1) {
			system("cls");

			return 2;
			break;
		}
		if (menu == 2) {
			system("cls");

			return 3;
			break;
		}
		if (menu == 3) {
			system("cls");

			return 4;
			break;
		}
		else if (menu == 4)
		{
			isRunning = 0;


		}
	}

	return 0;
}

